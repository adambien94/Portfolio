import { createHash } from "node:crypto";
import { watch } from "node:fs";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { spawn } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const publicDir = path.join(__dirname, "../public");
const outputFile = path.join(__dirname, "../src/data/image-blur-data.ts");

const IMAGE_EXTENSIONS = new Set([".webp", ".png", ".jpg", ".jpeg"]);

async function collectImageFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      files.push(...(await collectImageFiles(fullPath)));
      continue;
    }

    if (IMAGE_EXTENSIONS.has(path.extname(entry.name).toLowerCase())) {
      files.push(fullPath);
    }
  }

  return files;
}

function createContentHash(buffer) {
  return createHash("sha256").update(buffer).digest("hex").slice(0, 8);
}

async function createBlurDataURL(buffer) {
  const resized = await sharp(buffer).resize(16).webp({ quality: 20 }).toBuffer();

  return `data:image/webp;base64,${resized.toString("base64")}`;
}

async function generate() {
  const imageFiles = await collectImageFiles(publicDir);
  const blurData = {};
  const versionData = {};

  for (const filePath of imageFiles.sort()) {
    const buffer = await readFile(filePath);
    const publicPath = `/${path.relative(publicDir, filePath).split(path.sep).join("/")}`;

    blurData[publicPath] = await createBlurDataURL(buffer);
    versionData[publicPath] = createContentHash(buffer);
  }

  const fileContents = `// Generated by scripts/generate-blur-data.mjs - do not edit manually.

export const imageBlurData: Record<string, string> = ${JSON.stringify(blurData, null, 2)};

export const imageVersions: Record<string, string> = ${JSON.stringify(versionData, null, 2)};
`;

  await writeFile(outputFile, fileContents);
  console.log(
    `Generated blur data and versions for ${imageFiles.length} images → src/data/image-blur-data.ts`,
  );
}

function debounce(fn, delayMs) {
  let timeoutId;

  return (...args) => {
    clearTimeout(timeoutId);
    timeoutId = setTimeout(() => fn(...args), delayMs);
  };
}

function startDevServer() {
  const nextBin = path.join(__dirname, "../node_modules/next/dist/bin/next");
  const child = spawn(process.execPath, [nextBin, "dev"], {
    stdio: "inherit",
    cwd: path.join(__dirname, ".."),
  });

  child.on("exit", (code) => {
    process.exit(code ?? 0);
  });
}

async function watchImages() {
  await generate();
  startDevServer();

  const regenerate = debounce(async (event, filename) => {
    if (!filename || !IMAGE_EXTENSIONS.has(path.extname(filename).toLowerCase())) {
      return;
    }

    try {
      await generate();
    } catch (error) {
      console.error("Failed to regenerate image metadata:", error);
    }
  }, 300);

  watch(publicDir, { recursive: true }, regenerate);
  console.log("Watching public/ for image changes...");
}

const isWatchMode = process.argv.includes("--watch");

if (isWatchMode) {
  await watchImages();
} else {
  await generate();
}
